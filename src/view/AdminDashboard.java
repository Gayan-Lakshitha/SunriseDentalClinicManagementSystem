    private void btnAddUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddUserActionPerformed
        // TODO add your handling code here:
String name = txtName.getText().trim();
String email = txtEmail.getText().trim();
String contact = txtContact.getText().trim();

String role = cmbRole.getSelectedItem().toString();

String password =
        new String(txtPassword.getPassword());

String confirmPassword =
        new String(txtConfirmPassword.getPassword());

if (name.isEmpty()
        || email.isEmpty()
        || contact.isEmpty()
        || password.isEmpty()
        || confirmPassword.isEmpty()
        || role.equals("Select Role")) {

    JOptionPane.showMessageDialog(this,
            "Please fill in all fields.");

    return;
}

if (!name.matches("[A-Za-z. ]+")) {

    JOptionPane.showMessageDialog(this,
            "Name can contain letters and spaces only.");

    return;
}

String nameWithoutSpaces = name.replaceAll("\\s+", "");

if (nameWithoutSpaces.length() < 3) {

    JOptionPane.showMessageDialog(this,
            "Name must contain at least 3 letters.");

    return;
}

String emailPattern =
        "^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$";

if (!email.matches(emailPattern)) {

    JOptionPane.showMessageDialog(this,
            "Please enter a valid email address.");

    return;
}

if (!contact.matches("\\d{10}")) {

    JOptionPane.showMessageDialog(this,
            "Contact number must contain exactly 10 digits.");

    return;
}

if (password.length() < 8) {

    JOptionPane.showMessageDialog(this,
            "Password must contain at least 8 characters.");

    return;
}

if (!password.equals(confirmPassword)) {

    JOptionPane.showMessageDialog(this,
            "Passwords do not match.");

    return;
}

UserModel user = new UserModel();

user.setName(name);
user.setEmail(email);
user.setContactNo(contact);
user.setRole(role);
user.setPassword(password);

UserDAO dao = new UserDAO();

boolean result = dao.registerUser(user);

if (result) {

    JOptionPane.showMessageDialog(this,
            role + " added successfully!");

    clearFields();

} else {

    JOptionPane.showMessageDialog(this,
            "Unable to add user. Email may already exist.");
}
    }//GEN-LAST:event_btnAddUserActionPerformed

