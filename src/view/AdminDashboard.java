    private void loadUsers() {

    DefaultTableModel model =
            (DefaultTableModel) tblUsers.getModel();

    model.setRowCount(0);
    UserDAO dao =
            new UserDAO();
    userList =
            dao.getAllUsers();

    for (UserModel user : userList) {

        model.addRow(new Object[]{

            user.getUserId(),
            user.getName(),
            user.getEmail(),
            user.getContactNo(),
            user.getRole(),
            user.getPassword()
        });
    }
}
