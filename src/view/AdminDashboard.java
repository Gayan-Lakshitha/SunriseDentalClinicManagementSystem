    private void btnUpdateUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateUserActionPerformed
        if (txtUserId.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a user first.",
                "Update User",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }


    
    String name =
            txtname.getText().trim();
    String email =
            txtemail.getText().trim();
    String contact =
            txtcontact.getText().trim();
    String role =
            cmbrole.getSelectedItem().toString();
    String password =
            txtpassword.getText().trim();
   
    if (name.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter the user's name."
        );
        txtName.requestFocus();
        return;
    }

    if (email.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter the email address."
        );
        txtEmail.requestFocus();
        return;
    }

    if (contact.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter the contact number."
        );
        txtContact.requestFocus();
        return;
    }
    if (!contact.matches("\\d+")) {

        JOptionPane.showMessageDialog(
                this,
                "Contact number must contain numbers only."
        );
        txtContact.requestFocus();
        return;
    }

    if (contact.length() != 10) {

        JOptionPane.showMessageDialog(
                this,
                "Contact number must contain exactly 10 digits."
        );
        txtContact.requestFocus();
        return;
    }

    if (role.equals("Select Role")) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a role."
        );
        return;
    }
    if (password.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter the password."
        );
        txtPassword.requestFocus();
        return;
    }
    if (password.length() < 8) {

        JOptionPane.showMessageDialog(
                this,
                "Password must contain at least 8 characters."
        );
        txtPassword.requestFocus();
        return;
    }
    UserModel user =
            new UserModel();

    user.setUserId(
            Integer.parseInt(
                    txtUserId.getText()
            )
    );
    user.setName(name);
    user.setEmail(email);
    user.setContactNo(contact);
    user.setRole(role);
    user.setPassword(password);
    
    UserDAO dao =
            new UserDAO();

    boolean result =
            dao.updateUser(user);

    if (result) {

        JOptionPane.showMessageDialog(
                this,
                "User updated successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );
        loadUsers();
        clearUserFields();
    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to update user.",
                "Update Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnUpdateUserActionPerformed

    private void btnDeleteUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteUserActionPerformed
         if (txtUserId.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a user first.",
                "Delete User",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }
    int userId =
            Integer.parseInt(
                    txtUserId.getText()
            );
    if (userId == Session.getUserId()) {

    JOptionPane.showMessageDialog(
            this,
            "You cannot delete your own account.",
            "Delete Not Allowed",
            JOptionPane.WARNING_MESSAGE
    );

    return;
    }
    String name =
            txtName.getText().trim();

    int choice =
            JOptionPane.showConfirmDialog(
                    this,
                    "Are you sure you want to delete\n"
                    + "User: " + name
                    + "\nUser ID: " + userId
                    + "?",
                    "Confirm Delete",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE
            );
    if (choice != JOptionPane.YES_OPTION) {

        return;
    }
    UserDAO dao =
            new UserDAO();

    boolean result =
            dao.deleteUser(userId);

    if (result) {

        JOptionPane.showMessageDialog(
                this,
                "User deleted successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );
        loadUsers();
        clearUserFields();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Unable to delete user.\n"
                + "This user may be connected to existing "
                + "appointments or other records.",
                "Delete Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnDeleteUserActionPerformed

