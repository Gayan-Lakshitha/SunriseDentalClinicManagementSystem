   private void loadPatientDetails() {

    txtPatientName.setText(Session.getName());

    UserDAO dao = new UserDAO();

    UserModel user =
            dao.getUserById(Session.getUserId());

    if (user != null) {

        txtContact.setText(
                user.getContactNo()
        );
    }

    txtPatientName.setEditable(false);
    txtContact.setEditable(false);
}
   
   private void loadDoctors() {
    cmbDentist.removeAllItems();
    cmbDentist.addItem("Select Dentist");
    AppointmentDAO dao =
            new AppointmentDAO();
    doctorList = dao.getDoctors();
    for (UserModel doctor : doctorList) {
       cmbDentist.addItem(
                doctor.getName()
        );
    }
}
   
   private void loadAppointments() {

    DefaultTableModel model =
            (DefaultTableModel) tblAppointments.getModel();
    model.setRowCount(0);
    AppointmentDAO dao =
            new AppointmentDAO();
    ArrayList<AppointmentModel> list =
            dao.getPatientAppointments(
                    Session.getUserId()
            );

    for (AppointmentModel appointment : list) {

        model.addRow(new Object[]{

            appointment.getAppointmentNo(),
            appointment.getPatientName(),
            appointment.getContactNo(),
            appointment.getAddress(),
            appointment.getDentistName(),
            appointment.getAppointmentDate(),
            appointment.getAppointmentTime(),
            appointment.getStatus()
        });
    }
}
   
   private void loadMyBills() {

    DefaultTableModel model =
            (DefaultTableModel)
            tblMyBills.getModel();

    model.setRowCount(0);

    BillDAO dao =
            new BillDAO();

    ArrayList<BillModel> list =
            dao.getPatientBills(
                    Session.getUserId()
            );

    for (BillModel bill : list) {

        model.addRow(new Object[]{

            bill.getBillId(),

            bill.getAppointmentNo(),

            String.format(
                    "Rs. %.2f",
                    bill.getTreatmentTotal()
            ),

            String.format(
                    "Rs. %.2f",
                    bill.getConsultationFee()
            ),

            String.format(
                    "Rs. %.2f",
                    bill.getGrandTotal()
            ),

            String.format(
                    "Rs. %.2f",
                    bill.getPayment()
            ),

            String.format(
                    "Rs. %.2f",
                    bill.getBalance()
            ),

            bill.getPaymentStatus(),

            bill.getBillDate()
        });
    }
}
   
   private void clearFields() {
    txtAddress.setText("");
    cmbDentist.setSelectedIndex(0);
    txtDate.setText("");
    txtAddress.requestFocus();
}
    
