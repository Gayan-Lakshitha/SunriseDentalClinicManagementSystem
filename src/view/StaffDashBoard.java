    private void btnCalculateBalanceActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateBalanceActionPerformed
          if (billAppointmentNo <= 0) {

        JOptionPane.showMessageDialog(
                this,
                "Please search for an appointment first.",
                "Appointment Required",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    String paymentText =
            txtPayment.getText().trim();

    if (paymentText.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter the payment amount.",
                "Payment Required",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

      try {

        paymentAmount =
                Double.parseDouble(paymentText);

        if (paymentAmount < 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Payment cannot be negative.",
                    "Invalid Payment",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        if (paymentAmount >= grandTotal) {

            balanceAmount =
                    paymentAmount - grandTotal;

            paymentStatus = "Paid";

            lblBalance.setText(
                    "Change: Rs. "
                    + String.format(
                            "%.2f",
                            balanceAmount
                    )
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Payment received successfully.\n"
                    + "Change: Rs. "
                    + String.format(
                            "%.2f",
                            balanceAmount
                    ),
                    "Payment Successful",
                    JOptionPane.INFORMATION_MESSAGE
            );

        } else {

            balanceAmount =
                    grandTotal - paymentAmount;

            paymentStatus = "Pending";

            lblBalance.setText(
                    "Remaining: Rs. "
                    + String.format(
                            "%.2f",
                            balanceAmount
                    )
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Payment is incomplete.\n"
                    + "Remaining Amount: Rs. "
                    + String.format(
                            "%.2f",
                            balanceAmount
                    ),
                    "Payment Pending",
                    JOptionPane.WARNING_MESSAGE
            );
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter a valid number.",
                "Invalid Payment",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnCalculateBalanceActionPerformed

