    private void loadAppointments() {

    DefaultTableModel model =
            (DefaultTableModel) tblAppointments.getModel();

    model.setRowCount(0);

    AppointmentDAO dao = new AppointmentDAO();

    ArrayList<AppointmentModel> list =
            dao.getAllAppointments();

    for (AppointmentModel appointment : list) {

        model.addRow(new Object[]{

            appointment.getAppointmentNo(),
            appointment.getPatientName(),
            appointment.getContactNo(),
            appointment.getAddress(),
            appointment.getDentistName(),
            appointment.getAppointmentDate(),
            appointment.getAppointmentTime(),
            appointment.getStatus()
        });
    }
}
    
    private void loadBillAppointmentDetails() {

    AppointmentDAO appointmentDAO =
            new AppointmentDAO();

    AppointmentModel appointment =
            appointmentDAO.getAppointmentByNo(
                    billAppointmentNo
            );

    if (appointment == null) {

        JOptionPane.showMessageDialog(
                this,
                "Appointment not found.",
                "Not Found",
                JOptionPane.ERROR_MESSAGE
        );

        clearBillingDetails();

        return;
    }
     billPatientId =
            appointment.getPatientId();

    
    lblBillPatientID.setText(
            String.valueOf(
                    appointment.getPatientId()
            )
    );
    loadBillTreatments();
    calculateBill();
}
    
    private void calculateBill() {

    grandTotal =
            treatmentTotal + consultationFee;

    lblTreatmentTotal.setText(
            String.format(
                    "Rs. %.2f",
                    treatmentTotal
            )
    );

    lblConsultationFee.setText(
            String.format(
                    "Rs. %.2f",
                    consultationFee
            )
    );

    lblGrandTotal.setText(
            String.format(
                    "Rs. %.2f",
                    grandTotal
            )
    );

    lblBalance.setText("Rs. 0.00");
}
    
