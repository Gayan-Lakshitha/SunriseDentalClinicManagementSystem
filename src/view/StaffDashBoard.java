    private void tblAppointmentsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblAppointmentsMouseClicked
        // TODO add your handling code here:
        int row = tblAppointments.getSelectedRow();

    if (row == -1) {
        return;
    }

    txtAppointmentNo.setText(
            tblAppointments.getValueAt(row, 0).toString()
    );

    txtPatientName.setText(
            tblAppointments.getValueAt(row, 1).toString()
    );

    txtContactNum.setText(
            tblAppointments.getValueAt(row, 2).toString()
    );

    txtAddress.setText(
            tblAppointments.getValueAt(row, 3).toString()
    );

    String dentist =
            tblAppointments.getValueAt(row, 4).toString();

    cmbDentist.setSelectedItem(dentist);

    txtDate.setText(
            tblAppointments.getValueAt(row, 5).toString()
    );

    Object timeValue =
            tblAppointments.getValueAt(row, 6);

    if (timeValue != null) {

        txtTime.setText(timeValue.toString());

    } else {

        txtTime.setText("");
    }

    cmbStatus.setSelectedItem(
            tblAppointments.getValueAt(row, 7).toString()
    );
    }//GEN-LAST:event_tblAppointmentsMouseClicked

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
         String search =
            txtSearchAppointmentNo.getText().trim();

    if (search.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please enter an appointment number.");

        return;
    }

    try {

        int appointmentNo =
                Integer.parseInt(search);

        AppointmentDAO dao =
                new AppointmentDAO();

        AppointmentModel appointment =
                dao.searchAppointment(appointmentNo);

        if (appointment == null) {

            JOptionPane.showMessageDialog(this,
                    "Appointment not found.");

            return;
        }

        displayAppointment(appointment);

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Appointment number must contain numbers only.");
    }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (txtAppointmentNo.getText().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please select an appointment first.");

        return;
    }

    String address = txtAddress.getText().trim();

    String date = txtDate.getText().trim();

    String time = txtTime.getText().trim();

    String status =
            cmbStatus.getSelectedItem().toString();

    int selectedIndex =
            cmbDentist.getSelectedIndex();

    if (address.isEmpty()
            || date.isEmpty()
            || selectedIndex <= 0) {

        JOptionPane.showMessageDialog(this,
                "Please fill in all required fields.");

        return;
    }

    UserModel doctor =
            doctorList.get(selectedIndex - 1);

    int appointmentNo =
            Integer.parseInt(
                    txtAppointmentNo.getText()
            );

    AppointmentModel appointment =
            new AppointmentModel();

    appointment.setAppointmentNo(appointmentNo);
    appointment.setAddress(address);
    appointment.setDentistId(doctor.getUserId());
    appointment.setAppointmentDate(date);
    appointment.setAppointmentTime(time);
    appointment.setStatus(status);

    AppointmentDAO dao =
            new AppointmentDAO();

    boolean result =
            dao.updateAppointment(appointment);

    if (result) {

        JOptionPane.showMessageDialog(this,
                "Appointment updated successfully.");

        loadAppointments();

        clearFields();

    } else {

        JOptionPane.showMessageDialog(this,
                "Appointment update failed.");
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (txtAppointmentNo.getText().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please select an appointment first.");

        return;
    }

    int choice = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this appointment?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
    );

    if (choice != JOptionPane.YES_OPTION) {

        return;
    }

    int appointmentNo =
            Integer.parseInt(
                    txtAppointmentNo.getText()
            );

    AppointmentDAO dao =
            new AppointmentDAO();

    boolean result =
            dao.deleteAppointment(appointmentNo);

    if (result) {

        JOptionPane.showMessageDialog(this,
                "Appointment deleted successfully.");

        loadAppointments();

        clearFields();

    } else {

        JOptionPane.showMessageDialog(this,
                "Appointment deletion failed.");
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

