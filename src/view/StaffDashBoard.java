    private void loadDoctors() {

    cmbDentist.removeAllItems();

    cmbDentist.addItem("Select Dentist");

    AppointmentDAO dao = new AppointmentDAO();

    doctorList = dao.getDoctors();

    for (UserModel doctor : doctorList) {

        cmbDentist.addItem(doctor.getName());
    }
}
    
    private void loadAppointments() {

    DefaultTableModel model =
            (DefaultTableModel) tblAppointments.getModel();

    model.setRowCount(0);

    AppointmentDAO dao = new AppointmentDAO();

    ArrayList<AppointmentModel> list =
            dao.getAllAppointments();

    for (AppointmentModel appointment : list) {

        model.addRow(new Object[]{

            appointment.getAppointmentNo(),
            appointment.getPatientName(),
            appointment.getContactNo(),
            appointment.getAddress(),
            appointment.getDentistName(),
            appointment.getAppointmentDate(),
            appointment.getAppointmentTime(),
            appointment.getStatus()
        });
    }
}
    
    private void displayAppointment(AppointmentModel appointment) {

    txtAppointmentNo.setText(
            String.valueOf(
                    appointment.getAppointmentNo()
            )
    );

    txtPatientName.setText(
            appointment.getPatientName()
    );

    txtContactNum.setText(
            appointment.getContactNo()
    );

    txtAddress.setText(
            appointment.getAddress()
    );

    cmbDentist.setSelectedItem(
            appointment.getDentistName()
    );

    txtDate.setText(
            appointment.getAppointmentDate()
    );

    if (appointment.getAppointmentTime() != null) {

        txtTime.setText(
                appointment.getAppointmentTime()
        );

    } else {

        txtTime.setText("");
    }

    cmbStatus.setSelectedItem(
            appointment.getStatus()
    );
}
    
    private void clearFields() {

    txtName.setText("");
    txtEmail.setText("");
    txtContact.setText("");
    txtPassword.setText("");
    txtConfirmPassword.setText("");

    txtName.requestFocus();
}
